/**
 * A stand-in for xterm.js in tests: jsdom has no canvas or layout, which the
 * real emulator measures with. It records what's written and lets tests
 * type, and answers cursor position queries as xterm.js does.
 */
type Listener<T> = (value: T) => void

const CURSOR_QUERY = '\x1b[6n'

export class FakeTerminal {
  static instances: FakeTerminal[] = []

  cols = 80
  rows = 24
  element: HTMLElement | undefined
  textarea: HTMLTextAreaElement | undefined
  /** Everything written, in order. */
  written: string[] = []
  cleared = false
  disposed = false
  selection = false
  private currentOptions: Record<string, unknown>
  private readonly dataListeners: Listener<string>[] = []
  private readonly resizeListeners: Listener<{ cols: number; rows: number }>[] = []
  private readonly titleListeners: Listener<string>[] = []
  keyHandler: ((event: KeyboardEvent) => boolean) | undefined

  constructor(options: Record<string, unknown> = {}) {
    this.currentOptions = { ...options }
    FakeTerminal.instances.push(this)
  }

  get options(): Record<string, unknown> {
    return this.currentOptions
  }

  set options(options: Record<string, unknown>) {
    this.currentOptions = { ...this.currentOptions, ...options }
  }

  loadAddon(): void {}

  /** OSC handlers by code, as the real parser keeps them. */
  readonly oscHandlers = new Map<number, (data: string) => boolean>()
  readonly parser = {
    registerOscHandler: (code: number, handler: (data: string) => boolean) => {
      this.oscHandlers.set(code, handler)
      return { dispose: () => this.oscHandlers.delete(code) }
    },
  }
  linkProviders: unknown[] = []

  registerLinkProvider(provider: unknown) {
    this.linkProviders.push(provider)
    return { dispose: () => {} }
  }

  attachCustomKeyEventHandler(handler: (event: KeyboardEvent) => boolean): void {
    this.keyHandler = handler
  }

  onData(listener: Listener<string>) {
    this.dataListeners.push(listener)
    return { dispose: () => {} }
  }

  onResize(listener: Listener<{ cols: number; rows: number }>) {
    this.resizeListeners.push(listener)
    return { dispose: () => {} }
  }

  onTitleChange(listener: Listener<string>) {
    this.titleListeners.push(listener)
    return { dispose: () => {} }
  }

  write(data: string, callback?: () => void): void {
    this.written.push(data)
    for (let i = 0; i < data.split(CURSOR_QUERY).length - 1; i++) {
      this.type('\x1b[1;1R')
    }
    callback?.()
  }

  open(parent: HTMLElement): void {
    const element = document.createElement('div')
    element.className = 'xterm'
    const textarea = document.createElement('textarea')
    textarea.setAttribute('aria-label', 'Terminal input')
    element.append(textarea)
    parent.append(element)
    this.element = element
    this.textarea = textarea
  }

  focus(): void {
    this.textarea?.focus()
  }

  hasSelection(): boolean {
    return this.selection
  }

  clear(): void {
    this.cleared = true
  }

  dispose(): void {
    this.disposed = true
    this.element?.remove()
  }

  /** Test helper: input as if typed (or generated by the emulator). */
  type(data: string): void {
    for (const listener of this.dataListeners) {
      listener(data)
    }
  }

  /** Test helper: the shell set the title. */
  setTitle(title: string): void {
    for (const listener of this.titleListeners) {
      listener(title)
    }
  }

  /** Test helper: everything written, joined. */
  text(): string {
    return this.written.join('')
  }
}

export class FakeFitAddon {
  activate(): void {}
  dispose(): void {}
  fit(): void {}
}
